#include<bits/stdc++.h>
using namespace std;

int main() {    
    //  for
    for (int i = 1; i <= 5; i++) { // i++ -> i =  + 1
        cout << i << " ";
    }

    // while 
    int i = 1;
    while (i <= 5) {
        cout << i << " ";
        i++;
    }

    // do while
    int j = 1;
    do {
        cout << j << " ";
        j++;
    } while (j <= 5);

    return 0;
}